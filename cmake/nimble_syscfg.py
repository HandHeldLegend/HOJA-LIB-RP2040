"""NimBLE's settings as a C header: the defaults its controller and radio driver declare.

    python nimble_syscfg.py <nimble checkout> <out.h>

NimBLE keeps its build settings in syscfg.yml files that Mynewt's own build tool turns into
MYNEWT_VAL_* macros. Outside Mynewt nothing does, and the header its porting folder ships covers
the host only. This writes each default as an #ifndef'd macro, so the settings a build sets itself
(include/hal/nrf52/nimble/syscfg/syscfg.h) come first and win.

The files also hold settings that depend on others: "syscfg.defs.<condition>" declares one only when
the condition holds (BLE_LL_PHY, once a second PHY is on), and "syscfg.vals.<condition>" changes a
default (vendor HCI on, in a controller build). Both are written as #if blocks after the defaults
they test. A changed default leaves alone a setting the build set itself.
"""
import re
import sys

import yaml

SOURCES = (
    "nimble/syscfg.yml",
    "nimble/controller/syscfg.yml",
    "nimble/drivers/nrf5x/syscfg.yml",
    "nimble/transport/syscfg.yml",
)


def macro_value(value):
    if isinstance(value, bool):
        return "1" if value else "0"
    text = str(value).strip()
    # One setting defaulting to another: named directly, since the preprocessor won't expand
    # MYNEWT_VAL() inside its own expansion
    text = re.sub(r"MYNEWT_VAL_CHOICE\(\s*(\w+)\s*,\s*(\w+)\s*\)", r"MYNEWT_VAL_\g<1>__\g<2>", text)
    return re.sub(r"MYNEWT_VAL\(\s*(\w+)\s*\)", r"MYNEWT_VAL_\g<1>", text)


def condition(text):
    """A syscfg condition (BLE_PHY_2M || BLE_PHY_CODED) as a preprocessor expression."""
    return re.sub(r"\b[A-Za-z_][A-Za-z0-9_]*\b", lambda m: "MYNEWT_VAL_" + m.group(0), text.strip().strip("'\""))


def main():
    root, out_path = sys.argv[1], sys.argv[2]
    lines = [
        "/* Generated by cmake/nimble_syscfg.py from NimBLE's syscfg.yml files: do not edit */",
        "#ifndef HOJA_NIMBLE_SYSCFG_DEFAULTS_H",
        "#define HOJA_NIMBLE_SYSCFG_DEFAULTS_H",
        "",
    ]
    files = []
    for source in SOURCES:
        with open(f"{root}/{source}", encoding="utf-8") as f:
            files.append((source, yaml.safe_load(f) or {}))

    # What the build set itself, noted before any default defines it
    changed = sorted({name for _, doc in files for key, vals in doc.items()
                      if key.startswith("syscfg.vals") and isinstance(vals, dict) for name in vals})
    lines.append("/* Set by the build: a changed default leaves these alone */")
    for name in changed:
        lines += [f"#ifdef MYNEWT_VAL_{name}", f"#define HOJA_NIMBLE_SET_{name}", "#endif"]
    lines.append("")

    conditional = []
    for source, doc in files:
        for key, entries in doc.items():
            if not isinstance(entries, dict):
                continue
            if key.startswith("syscfg.defs."):
                when = condition(key[len("syscfg.defs."):])
                for name, entry in entries.items():
                    value = entry.get("value") if isinstance(entry, dict) else entry
                    conditional += [f"#if ({when}) && !defined(MYNEWT_VAL_{name})",
                                    f"#define MYNEWT_VAL_{name} ({macro_value(value)})", "#endif"]
            elif key.startswith("syscfg.vals"):
                when = condition(key[len("syscfg.vals."):]) if key != "syscfg.vals" else "1"
                for name, value in entries.items():
                    conditional += [f"#if ({when}) && !defined(HOJA_NIMBLE_SET_{name})",
                                    f"#undef MYNEWT_VAL_{name}",
                                    f"#define MYNEWT_VAL_{name} ({macro_value(value)})", "#endif"]

    for source, doc in files:
        defs = doc.get("syscfg.defs", {}) or {}
        lines.append(f"/* {source} */")
        for name, entry in defs.items():
            if not isinstance(entry, dict):
                entry = {"value": entry}
            value = entry.get("value")
            choices = entry.get("choices")
            if choices:
                # A choice is on (1) and names which of its options is
                lines += [f"#ifndef MYNEWT_VAL_{name}", f"#define MYNEWT_VAL_{name} 1", "#endif"]
                for choice in choices:
                    on = 1 if str(choice) == str(value) else 0
                    lines += [f"#ifndef MYNEWT_VAL_{name}__{choice}",
                              f"#define MYNEWT_VAL_{name}__{choice} {on}", "#endif"]
                continue
            if value is None or macro_value(value) == "":
                # Unset: left undefined, which reads as 0 in #if
                continue
            lines += [f"#ifndef MYNEWT_VAL_{name}", f"#define MYNEWT_VAL_{name} ({macro_value(value)})", "#endif"]
        lines.append("")
    lines.append("/* Settings that depend on others */")
    lines += conditional
    lines.append("")
    lines.append("#endif")
    with open(out_path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
